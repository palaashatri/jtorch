package org.jtorch.optim;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.jtorch.api.Torch;
import org.jtorch.core.Shape;
import org.jtorch.core.Tensor;
import org.jtorch.core.TensorOptions;
import org.jtorch.json.Json;
import org.jtorch.nn.Parameter;
import org.junit.jupiter.api.Test;

/** Differential optimizer test against fixtures generated by the pinned PyTorch runtime. */
class OptimizerOracleTest {
    @Test
    void updateRulesMatchPyTorch() throws IOException {
        Map<String, Object> document = Json.parseObject(read("/optimizers.json"));
        for (Object raw : Json.array(document.get("cases"))) {
            Map<String, Object> testCase = Json.object(raw);
            String name = Json.string(testCase.get("optimizer"));
            Map<String, Object> configuration = Json.object(testCase.get("configuration"));
            double[] initial = doubles(testCase.get("initial"));
            long[] shape = longs(testCase.get("shape"));
            Parameter parameter = new Parameter(Torch.tensor(initial, Shape.of(shape),
                    TensorOptions.defaults().dtype(org.jtorch.core.DType.FLOAT64)));
            Optimizer optimizer = create(name, configuration, parameter);
            for (Object stepRaw : Json.array(testCase.get("steps"))) {
                Map<String, Object> step = Json.object(stepRaw);
                double[] gradient = doubles(step.get("grad"));
                parameter.impl().setGrad(Torch.tensor(gradient, Shape.of(shape),
                        TensorOptions.defaults().dtype(org.jtorch.core.DType.FLOAT64)));
                optimizer.step();
                assertArrayEquals(doubles(step.get("expected")), parameter.toDoubleArray(), 1e-12,
                        name + " parameter update");
            }
        }
    }

    @Test
    void schedulersUseTheDocumentedFormula() {
        Parameter parameter = new Parameter(Torch.zeros(Shape.of(2)));
        SGD optimizer = SGD.builder().parameters(List.of(parameter)).learningRate(0.1).build();
        StepLR scheduler = new StepLR(optimizer, 2, 0.5);
        assertTrue(optimizer.learningRate() == 0.1);
        scheduler.step();
        assertTrue(optimizer.learningRate() == 0.1);
        scheduler.step();
        assertTrue(optimizer.learningRate() == 0.05);
        scheduler.step();
        scheduler.step();
        assertTrue(Math.abs(optimizer.learningRate() - 0.025) < 1e-15);

        Parameter other = new Parameter(Torch.zeros(Shape.of(1)));
        SGD otherOptimizer = SGD.builder().parameters(List.of(other)).learningRate(0.2).build();
        ExponentialLR exponential = new ExponentialLR(otherOptimizer, 0.5);
        exponential.step();
        assertTrue(Math.abs(otherOptimizer.learningRate() - 0.1) < 1e-15);
    }

    private static Optimizer create(String name, Map<String, Object> configuration, Parameter parameter) {
        double learningRate = Json.doubleValue(configuration.get("learningRate"));
        double weightDecay = configuration.containsKey("weightDecay")
                ? Json.doubleValue(configuration.get("weightDecay"))
                : 0.0;
        return switch (name) {
            case "sgd" -> SGD.builder()
                    .parameters(List.of(parameter))
                    .learningRate(learningRate)
                    .weightDecay(weightDecay)
                    .build();
            case "sgd-momentum" -> SGD.builder()
                    .parameters(List.of(parameter))
                    .learningRate(learningRate)
                    .momentum(Json.doubleValue(configuration.get("momentum")))
                    .weightDecay(weightDecay)
                    .build();
            case "sgd-nesterov" -> SGD.builder()
                    .parameters(List.of(parameter))
                    .learningRate(learningRate)
                    .momentum(Json.doubleValue(configuration.get("momentum")))
                    .nesterov(Json.booleanValue(configuration.get("nesterov")))
                    .build();
            case "adam" -> Adam.builder()
                    .parameters(List.of(parameter))
                    .learningRate(learningRate)
                    .weightDecay(weightDecay)
                    .build();
            case "adamw" -> AdamW.builder()
                    .parameters(List.of(parameter))
                    .learningRate(learningRate)
                    .weightDecay(weightDecay)
                    .build();
            default -> throw new IllegalArgumentException("Unknown optimizer fixture " + name);
        };
    }

    private static double[] doubles(Object value) {
        List<Object> raw = Json.array(value);
        double[] result = new double[raw.size()];
        for (int i = 0; i < result.length; i++) {
            result[i] = Json.doubleValue(raw.get(i));
        }
        return result;
    }

    private static long[] longs(Object value) {
        List<Object> raw = Json.array(value);
        long[] result = new long[raw.size()];
        for (int i = 0; i < result.length; i++) {
            result[i] = Json.longValue(raw.get(i));
        }
        return result;
    }

    private static String read(String resource) throws IOException {
        try (InputStream stream = OptimizerOracleTest.class.getResourceAsStream(resource)) {
            if (stream == null) {
                throw new IOException("Missing resource " + resource);
            }
            return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
        }
    }
}
